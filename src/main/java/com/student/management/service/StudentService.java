package com.student.management.service;

import com.student.management.entity.Student;
import com.student.management.exception.ResourceNotFoundException;
import com.student.management.repository.StudentRepository;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;

@Service
public class StudentService {

    private final StudentRepository repository;

    public StudentService(StudentRepository repository) {
        this.repository = repository;
    }

    public Student addStudent(Student student) {
        // ID is generated by MySQL; ignore any ID supplied by the client.
        student.setStudentId(null);
        return repository.save(student);
    }

    public List<Student> getAllStudents() {
        return repository.findAll();
    }

    public Student getStudentById(Integer id) {
        return repository.findById(id)
                .orElseThrow(() -> new ResourceNotFoundException(
                        "Student not found with ID: " + id));
    }

    public Student updateStudent(Integer id, Student updatedStudent) {
        Student existing = getStudentById(id);

        existing.setStudentName(updatedStudent.getStudentName());
        existing.setEmail(updatedStudent.getEmail());
        existing.setCourseName(updatedStudent.getCourseName());
        existing.setProgrammingScore(updatedStudent.getProgrammingScore());
        existing.setMathematicsScore(updatedStudent.getMathematicsScore());
        existing.setTechnicalSkills(updatedStudent.getTechnicalSkills());

        return repository.save(existing);
    }

    public void deleteStudent(Integer id) {
        Student student = getStudentById(id);
        repository.delete(student);
    }

    public List<Student> searchBySkill(String skill) {
        if (skill == null || skill.isBlank()) {
            throw new IllegalArgumentException("Skill cannot be empty");
        }
        return repository.searchByTechnicalSkill(skill.trim());
    }

    public List<Student> searchByCourse(String courseName) {
        if (courseName == null || courseName.isBlank()) {
            throw new IllegalArgumentException("Course name cannot be empty");
        }
        return repository.findByCourseNameIgnoreCase(courseName.trim());
    }

    // Demonstrates Java Collections: ArrayList, Comparator and sort().
    public List<Student> sortByAverage(boolean descending) {
        List<Student> students = new ArrayList<>(repository.findAll());

        Comparator<Student> comparator =
                Comparator.comparingDouble(Student::calculateAverage);

        if (descending) {
            comparator = comparator.reversed();
        }

        students.sort(comparator);
        return students;
    }

    public double calculateAverage(Integer id) {
        return getStudentById(id).calculateAverage();
    }

    @Transactional
    public Student addSkill(Integer id, String skill) {
        if (skill == null || skill.isBlank()) {
            throw new IllegalArgumentException("Skill cannot be empty");
        }

        Student student = getStudentById(id);
        student.addSkill(skill);
        return repository.save(student);
    }

    public long countStudents() {
        return repository.count();
    }
}
